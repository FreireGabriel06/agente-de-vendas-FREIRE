"""
Adds a client instance without editing YAML by hand.

    python3 novo_cliente.py            # next free name: cliente2, cliente3...
    python3 novo_cliente.py cliente-lojax

It creates instancias/<name>.env from instancia.exemplo.env (panel address
<name>.<DOMINIO>) and regenerates, from every instancias/*.env except
cliente1, the two files the stack reads (both ignored by git):

    docker-compose.override.yml    one service and one volume per client
    clientes-caddy/<name>.caddy    the HTTPS block that forwards to it

Then: create the client's operator, start it and reload Caddy (printed at
the end). With a wildcard DNS record (*.DOMINIO) no DNS change is needed.
"""
import re
import sys
from pathlib import Path

AQUI = Path(__file__).resolve().parent
NOME = re.compile(r"cliente[a-z0-9-]{0,30}")
FIXO = "cliente1"  # declared in docker-compose.yml
CABECALHO = "# Generated by novo_cliente.py from instancias/*.env. Do not edit; ignored by git.\n"


def dominio(pasta: Path) -> str:
    env = pasta / ".env"
    if env.exists():
        for linha in env.read_text(encoding="utf-8").splitlines():
            if linha.strip().startswith("DOMINIO="):
                valor = linha.split("=", 1)[1].strip().strip("\"'")
                if valor:
                    return valor
    raise SystemExit("Defina DOMINIO em deploy/.env primeiro (ex.: echo DOMINIO=suamarca.com > .env).")


def clientes(pasta: Path) -> list[str]:
    nomes = sorted(p.stem for p in (pasta / "instancias").glob("*.env"))
    return [n for n in nomes if NOME.fullmatch(n) and n != FIXO]


def proximo_nome(pasta: Path) -> str:
    usados = set(clientes(pasta)) | {FIXO}
    n = 2
    while f"cliente{n}" in usados:
        n += 1
    return f"cliente{n}"


def criar_env(pasta: Path, nome: str, dom: str) -> Path:
    destino = pasta / "instancias" / f"{nome}.env"
    if destino.exists():
        raise SystemExit(f"{destino.name} já existe.")
    modelo = (pasta / "instancia.exemplo.env").read_text(encoding="utf-8")
    destino.parent.mkdir(exist_ok=True)
    destino.write_text(modelo.replace("cliente1.example.com", f"{nome}.{dom}"), encoding="utf-8")
    return destino


def gerar(pasta: Path) -> list[str]:
    """Reescreve o override e os blocos do Caddy a partir de instancias/*.env."""
    nomes = clientes(pasta)
    linhas = [CABECALHO, "services:\n"] if nomes else [CABECALHO, "services: {}\n"]
    for n in nomes:
        linhas.append(
            f"  {n}:\n"
            "    build:\n"
            "      context: ..\n"
            "      dockerfile: deploy/Dockerfile\n"
            "    restart: unless-stopped\n"
            f"    env_file: instancias/{n}.env\n"
            "    environment:\n"
            "      PROXY_IPS: 172.30.0.2\n"
            "    volumes:\n"
            f"      - dados_{n}:/dados\n"
            "    networks:\n"
            "      - interna\n")
    if nomes:
        linhas.append("volumes:\n" + "".join(f"  dados_{n}:\n" for n in nomes))
    (pasta / "docker-compose.override.yml").write_text("".join(linhas), encoding="utf-8")

    caddy = pasta / "clientes-caddy"
    caddy.mkdir(exist_ok=True)
    for velho in caddy.glob("*.caddy"):
        if velho.stem not in nomes:
            velho.unlink()
    for n in nomes:
        (caddy / f"{n}.caddy").write_text(
            f"# Generated by novo_cliente.py.\n{n}.{{$DOMINIO}} {{\n\treverse_proxy {n}:8777\n}}\n",
            encoding="utf-8")
    return nomes


def main(argv: list[str], pasta: Path = AQUI) -> int:
    dom = dominio(pasta)
    nome = argv[0] if argv else proximo_nome(pasta)
    if not NOME.fullmatch(nome) or nome == FIXO:
        raise SystemExit("Nome inválido: use cliente2, cliente3 ou cliente-<letras/números> (até 36 caracteres).")
    criar_env(pasta, nome, dom)
    gerar(pasta)
    print(f"Cliente {nome}: painel em https://{nome}.{dom}")
    print("Próximos passos:")
    print(f"  docker compose run --rm {nome} python cli.py operador --usuario NOME")
    print(f"  docker compose run --rm -it {nome} python cli.py operador --usuario NOME --mfa-ativar")
    print(f"  docker compose up -d --build {nome}")
    print("  docker compose exec caddy caddy reload --config /etc/caddy/Caddyfile")
    print("No app da Amazon, acrescente as URIs:")
    print(f"  https://{nome}.{dom}/oauth/amazon/login")
    print(f"  https://{nome}.{dom}/oauth/amazon/retorno")
    print(f"No app do Mercado Livre, acrescente: https://{nome}.{dom}/oauth/ml/retorno")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
